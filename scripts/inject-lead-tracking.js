const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.resolve(__dirname, '..');
function buildConfig(env = process.env) {
  const containerId = (env.ZHONGGU_GTM_CONTAINER_ID || '').trim();
  const requested = env.ZHONGGU_GTM_ENABLED === 'true';
  if (requested && (!/^GTM-[A-Z0-9]+$/.test(containerId) || /^GTM-X+$/.test(containerId))) throw Error('Set a real ZHONGGU_GTM_CONTAINER_ID before enabling GTM');
  return { enabled: requested && (!env.CONTEXT || env.CONTEXT === 'production'), containerId: requested ? containerId : '' };
}
function inject(root = ROOT, env = process.env) {
  const config = buildConfig(env);
  fs.writeFileSync(path.join(root, 'assets/js/tracking-config.js'), '// Generated by scripts/inject-lead-tracking.js; IDs are public, never put secrets here.\nwindow.ZhongguTrackingConfig = ' + JSON.stringify(config) + ';\n');
  const block = '<!-- Zhonggu lead tracking -->\n  <script src="/assets/js/tracking-config.js"></script>\n  <script src="/assets/js/lead-tracking.js"></script>\n  <!-- /Zhonggu lead tracking -->';
  let count = 0;
  const walk = dir => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('.') || ['node_modules', 'tmp', 'admin', 'ops', 'data', 'media-inbox', 'media-processed', 'media-trash'].includes(entry.name)) continue;
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) { walk(file); continue; }
      if (!entry.isFile() || !entry.name.endsWith('.html') || /^(?:yandex_|google[a-f0-9]+\.html$|IMAGE_PREVIEW_INDEX\.html$)/i.test(entry.name)) continue;
      const before = fs.readFileSync(file, 'utf8');
      if (!/<head[ >]/i.test(before) || /http-equiv=["']refresh["']/i.test(before)) continue;
      const marker = /<!-- Zhonggu lead tracking -->[\s\S]*?<!-- \/Zhonggu lead tracking -->/;
      const after = marker.test(before) ? before.replace(marker, block) : before.replace(/<head([^>]*)>/i, '<head$1>\n  ' + block);
      if (before !== after) fs.writeFileSync(file, after);
      count++;
    }
  };
  walk(root);
  console.log('Lead tracking ready on ' + count + ' public pages; GTM enabled: ' + config.enabled);
}
if (require.main === module) inject();
module.exports = { buildConfig, inject };
